#!/usr/bin/env bash
# kody-celld container entrypoint. Modes:
#   single   local durable state under $KODY_STATE_DIR: deploy via celld.dev, then
#            exec the node directly (not a long-lived celld.dev; see issue #89)
#   deploy   render the fleet config from env and publish the Worker to $CELLD_BUCKET
#   node     run a fleet node against $CELLD_BUCKET (celld reads its own CELLD_* env)
#   celld    pass the remaining arguments straight to the celld binary
#   sh       drop into a shell
set -euo pipefail

mode="${1:-single}"
shift || true
state_dir="${KODY_STATE_DIR:-/data}"
port="${PORT:-8080}"

# Compose passes unset optional variables through as empty strings; celld wants
# them absent.
for optional in S3_ENDPOINT $(compgen -v | grep '^KODY_' || true); do
	if [[ -z "${!optional:-}" ]]; then unset "$optional"; fi
done

# Runtime limits / quota defaults (docs/operations.md) are plain KODY_* vars
# that the Worker reads from its bindings; list the ones that are set.
tunable_vars() {
	compgen -v | grep -E '^KODY_(EXECUTE|RUN|RESPONSE|AUDIT|MCP|QUOTA|AI|SEARCH|VECTOR|QDRANT|BLOB|BROWSER|WEBHOOK|EMAIL|NPM|ESM|PACKAGE|DNS|PRIVATE|APP)_' || true
}

random_hex() {
	node -e 'process.stdout.write(require("node:crypto").randomBytes(Number(process.argv[1])).toString("hex"))' "$1"
}

# Operator values live in $state_dir/kody.env so they survive image upgrades.
# Environment variables win over the file (and are written back to it, so a
# rotated master key sticks); missing values are generated once.
load_or_generate_operator_values() {
	local env_file="$state_dir/kody.env"
	local env_admin="${KODY_ADMIN_TOKEN:-}" env_master="${KODY_MASTER_KEY:-}"
	if [[ -f "$env_file" ]]; then
		# shellcheck disable=SC1090
		set -a && source "$env_file" && set +a
	fi
	local generated=0
	if [[ -n "$env_admin" && "$env_admin" != "${KODY_ADMIN_TOKEN:-}" ]]; then generated=1; fi
	if [[ -n "$env_master" && "$env_master" != "${KODY_MASTER_KEY:-}" ]]; then generated=1; fi
	if [[ -n "$env_admin" ]]; then KODY_ADMIN_TOKEN="$env_admin"; fi
	if [[ -n "$env_master" ]]; then KODY_MASTER_KEY="$env_master"; fi
	if [[ -z "${KODY_ADMIN_TOKEN:-}" ]]; then
		KODY_ADMIN_TOKEN="$(random_hex 32)"
		generated=1
	fi
	if [[ -z "${KODY_MASTER_KEY:-}" ]]; then
		KODY_MASTER_KEY="$(random_hex 32)"
		generated=1
	fi
	export KODY_ADMIN_TOKEN KODY_MASTER_KEY
	if [[ "$generated" == 1 || ! -f "$env_file" ]]; then
		mkdir -p "$state_dir"
		umask 077
		{
			echo "# Generated by kody-celld on $(date -u +%FT%TZ). Back this file up: losing"
			echo "# KODY_MASTER_KEY makes every stored user secret unreadable."
			echo "KODY_ADMIN_TOKEN=$KODY_ADMIN_TOKEN"
			echo "KODY_MASTER_KEY=$KODY_MASTER_KEY"
		} >"$env_file"
		umask 022
		echo "[kody-celld] wrote operator values to $env_file (admin token + master key)."
		echo "[kody-celld] read the admin token with: docker compose exec kody cat $env_file"
	fi
}

run_single() {
	load_or_generate_operator_values
	export KODY_PUBLIC_URL="${KODY_PUBLIC_URL:-http://localhost:$port}"
	mkdir -p "$state_dir/celld/dev"
	# Local durable state lives under <project>/.celld/dev (same layout celld.dev
	# uses). Point the project path at the volume so upgrades keep existing data.
	if [[ ! -L /app/.celld ]]; then
		rm -rf /app/.celld
		ln -s "$state_dir/celld" /app/.celld
	fi

	# Compose passes unset optional vars as empty strings. celld's env parser
	# treats "" as an invalid u64 for CELLD_LTX_RETENTION_SECS and aborts at
	# validate() (smoke saw celld.dev exit 1 before deploy/current.json).
	# Empty CELLD_DEV_FLAGS must also be absent so the deploy argv stays clean.
	if [[ -z "${CELLD_LTX_RETENTION_SECS:-}" ]]; then
		unset CELLD_LTX_RETENTION_SECS || true
	fi
	if [[ -z "${CELLD_DEV_FLAGS:-}" ]]; then
		unset CELLD_DEV_FLAGS || true
	fi

	# Epoch GC (denoland/celld#240): celld leaves CELLD_LTX_RETENTION_SECS unset,
	# which means no deletion. Threshold compaction only folds within the current
	# epoch, so superseded-epoch L0 prefixes accumulate forever in the local
	# store and make every cold restore's source lookup scan huge (issue #89).
	# celld's owner GC deletes only prefixes below the restore-chain base that
	# are proven unreachable (crates/logic/epoch_gc.rs). Default 1 day grace;
	# set CELLD_LTX_RETENTION_SECS=0 to keep celld's no-deletion default.
	#
	# Proof that GC runs on Docker `single` (not a multi-node fleet): there is
	# no CELLD_DURABILITY=single. celld only accepts `fleet` | `bucket`, and
	# defaults to `fleet`. Our entrypoint never sets durability. With
	# `--bucket celld-dev` + CELLD_INTERNAL_DEV_STORE, main.rs installs
	# DurabilityOwner::new(manager, durability == "fleet") and
	# start_background spawns node_log maintenance, whose tick calls
	# Manager::gc_superseded_epochs (crates/celld/node_log.rs). That pass is a
	# no-op unless CELLD_LTX_RETENTION_SECS is positive (LtxRepl::epoch_gc_grace_ms).
	# CELLD_DURABILITY=bucket skips spawn_maintenance entirely, so fail loudly.
	if [[ -z "${CELLD_LTX_RETENTION_SECS+x}" ]]; then
		export CELLD_LTX_RETENTION_SECS=86400
	fi
	case "${CELLD_DURABILITY:-fleet}" in
	fleet) ;;
	bucket)
		if [[ "${CELLD_LTX_RETENTION_SECS}" != "0" ]]; then
			echo "[kody-celld] error: CELLD_LTX_RETENTION_SECS=${CELLD_LTX_RETENTION_SECS} needs CELLD_DURABILITY=fleet (celld default); bucket durability never runs epoch GC" >&2
			exit 1
		fi
		;;
	*)
		echo "[kody-celld] error: CELLD_DURABILITY must be fleet or bucket (got ${CELLD_DURABILITY})" >&2
		exit 1
		;;
	esac

	# .dev.vars overrides wrangler.jsonc vars; the deploy step reads it beside
	# the config and bakes values into the Worker deployment. Email /
	# private-host / insecure-host smoke values are not in wrangler.jsonc, so
	# unset operator env leaves those features off (no public dev fallbacks).
	umask 077
	{
		echo "KODY_ADMIN_TOKEN=$KODY_ADMIN_TOKEN"
		echo "KODY_MASTER_KEY=$KODY_MASTER_KEY"
		echo "KODY_PUBLIC_URL=$KODY_PUBLIC_URL"
		if [[ -n "${KODY_MASTER_KEY_PREVIOUS:-}" ]]; then
			echo "KODY_MASTER_KEY_PREVIOUS=$KODY_MASTER_KEY_PREVIOUS"
		fi
		for tunable in $(tunable_vars); do
			echo "$tunable=${!tunable}"
		done
	} >/app/.dev.vars
	umask 022

	# Do not leave `celld.dev` as the long-running process. Its supervisor
	# waits a fixed ~30s for the child to announce its operator listener; a
	# large uncompacted local store can miss that window and crash-loop
	# (kody-hq/kody-celld#89). Deploy through celld.dev (only public writer
	# for the local store), then exec the node the same way celld.dev would.
	local single_state="$state_dir/celld/dev"
	# shellcheck disable=SC2086 # CELLD_DEV_FLAGS is an optional flag string for the deploy step only
	node /app/docker/single-local.mjs deploy \
		--project /app \
		--state "$single_state" \
		--host 127.0.0.1 \
		--port "$port" \
		-- ${CELLD_DEV_FLAGS:-}

	# Scrub fleet-oriented env so the local-dev store guard accepts this node.
	unset CELLD_BUCKET CELLD_ADDR CELLD_ADVERTISE CELLD_INTERNAL_ADDR \
		CELLD_CLOUD CELLD_TEST_BUCKET CELLD_TRUST_FORWARDED_HEADERS \
		CELLD_UNSAFE_PUBLIC_ADVERTISE S3_ENDPOINT AWS_REGION AWS_DEFAULT_REGION \
		CELLD_INTERNAL_DEV_STORE || true
	# shellcheck disable=SC1091
	eval "$(node /app/docker/single-local.mjs node-env --project /app --state "$single_state")"
	export CELLD_INTERNAL_DEV_STORE CELLD_WATCH CELLD_NODE

	echo "[kody-celld] single node: MCP at $KODY_PUBLIC_URL/mcp (listening on 0.0.0.0:$port)"
	echo "[kody-celld] single node: running celld directly against the local store (node=$CELLD_NODE, CELLD_LTX_RETENTION_SECS=$CELLD_LTX_RETENTION_SECS, CELLD_DURABILITY=${CELLD_DURABILITY:-fleet})"
	exec celld \
		--no-control-plane \
		--bucket celld-dev \
		--listen "0.0.0.0:$port" \
		--internal-listen 127.0.0.1:0
}

run_deploy() {
	: "${CELLD_BUCKET:?CELLD_BUCKET is required (s3://bucket[/prefix])}"
	if [[ "${KODY_CREATE_BUCKET:-0}" == 1 ]]; then
		node /app/docker/ensure-bucket.mjs
	fi
	node /app/scripts/render-fleet-config.mjs
	exec celld deploy /app/wrangler.fleet.jsonc "$@"
}

run_node() {
	: "${CELLD_BUCKET:?CELLD_BUCKET is required (s3://bucket[/prefix])}"
	export CELLD_ADDR="${CELLD_ADDR:-0.0.0.0:$port}"
	exec celld "$@"
}

case "$mode" in
single) run_single "$@" ;;
deploy) run_deploy "$@" ;;
node) run_node "$@" ;;
celld) exec celld "$@" ;;
sh | bash) exec bash "$@" ;;
*)
	echo "unknown mode '$mode' (expected single|deploy|node|celld|sh)" >&2
	exit 64
	;;
esac
